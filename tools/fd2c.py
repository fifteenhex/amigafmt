#!/usr/bin/env python3
"""
fd2c.py <lib.fd>... : turn AmigaOS .fd files into C tables.

For every function the table records its library vector offset (the bias
counted from ##bias in steps of 6), its name and its argument registers.
amigafmt binds its C implementations to vectors by NAME through these
tables, so no offset is ever written by hand.

With --lvo it prints #define LVO<Name> (-offset) lines instead, for the
test programs.
"""
import os
import re
import sys

lvo = sys.argv[1:2] == ['--lvo']
paths = sys.argv[2:] if lvo else sys.argv[1:]
out = ['/* generated by tools/fd2c.py - do not edit */']
if not lvo:
    out.append('#include "af.h"')
for path in paths:
    lib = os.path.basename(path).replace('_lib.fd', '')
    bias, ents = 0, []
    for line in open(path):
        line = line.strip()
        if line.startswith('##bias'):
            bias = int(line.split()[1])
        elif line.startswith('##') or line.startswith('*') or not line:
            continue
        else:
            m = re.match(r'(\w+)\((.*?)\)\((.*?)\)', line)
            if not m:
                sys.exit(f'{path}: cannot parse {line!r}')
            ents.append((bias, m.group(1), m.group(3).replace(',', '/')))
            bias += 6
    if lvo:
        for b, name, regs in ents:
            if 'Private' not in name and name != 'private':
                out.append(f'#define LVO{name} (-{b})')
        continue
    out.append(f'const struct fdent fd_{lib}[] = {{')
    for b, name, regs in ents:
        out.append(f'\t{{ {b}, "{name}", "{regs}" }},')
    out.append('\t{ 0, 0, 0 }\n};')
print('\n'.join(out))
